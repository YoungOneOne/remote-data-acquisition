/* ---------------------------------------------------------------------------
 *  死机诊断（黑匣子）
 *
 *  【为什么这里不再自己定义 HardFault_Handler】
 *      CubeMX 每次重新生成代码，都会在文件下面重新写一个标准的
 *      HardFault_Handler。如果这里再定义一个，就是重复定义 -> 编译报错。
 *      所以这里只提供 fault_report()，由下面那个生成函数里的
 *      USER CODE 区调用 —— 那段代码 CubeMX 不会动，重新生成也不会丢。
 *
 *  【能看到什么】
 *      CFSR 说明故障类型（MPU 越权 / 总线错误 / 非对齐 / 非法指令…）
 *      MMFAR、BFAR 是对应的出错地址
 *      比 PC 更好用：MPU 错时 PC 根本不可信
 * --------------------------------------------------------------------------- */
void fault_report(void)
{
  printf("\r\n!! FAULT CFSR=%08lX HFSR=%08lX MMFAR=%08lX BFAR=%08lX\r\n",
         (unsigned long)SCB->CFSR, (unsigned long)SCB->HFSR,
         (unsigned long)SCB->MMFAR, (unsigned long)SCB->BFAR);
  printf("        MSP=%08lX PSP=%08lX\r\n",
         (unsigned long)__get_MSP(), (unsigned long)__get_PSP());

  /* 把 CFSR 的常见标志翻译成人话 */
  if ((SCB->CFSR & (1u << 7))  != 0) printf("        -> MPU 越权访问，地址见 MMFAR\r\n");
  if ((SCB->CFSR & (1u << 10)) != 0) printf("        -> 写总线错误（延迟上报），地址不确定\r\n");
  if ((SCB->CFSR & (1u << 15)) != 0) printf("        -> 精确总线错误，地址见 BFAR\r\n");
  if ((SCB->CFSR & (1u << 24)) != 0) printf("        -> 非对齐访问\r\n");
  if ((SCB->CFSR & (1u << 16)) != 0) printf("        -> 非法指令\r\n");
  if ((SCB->CFSR & (1u << 1))  != 0) printf("        -> 指令访问违例\r\n");

  SCB->CFSR = 0xFFFFFFFFu;
  while (1) { }
}

